id current()
{
    const auto language = config::general_settings.language;
    return language > 0 && language < static_cast<int>(id::count) ? static_cast<id>(language) : id::en;
}

const char* code(id value)
{
    return value == id::pt_br ? "PT-BR" : (value == id::ru ? "RU" : "EN");
}

